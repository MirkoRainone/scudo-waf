-- ==========================================
-- 1. Tabella API Keys & Tenant Account
-- ==========================================
CREATE TABLE IF NOT EXISTS public.api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_string TEXT,
    key_hash TEXT UNIQUE,
    key_prefix TEXT,
    email TEXT NOT NULL,
    plan TEXT NOT NULL DEFAULT 'free',
    monthly_quota INTEGER NOT NULL DEFAULT 10000,
    used_this_month INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT true,
    stripe_customer_id TEXT,
    stripe_subscription_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Estensioni retrocompatibili nel caso la tabella api_keys esistesse già
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS key_string TEXT;
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS key_hash TEXT;
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS key_prefix TEXT;
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS email TEXT;
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS plan TEXT NOT NULL DEFAULT 'free';
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS monthly_quota INTEGER NOT NULL DEFAULT 10000;
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS used_this_month INTEGER NOT NULL DEFAULT 0;
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT true;
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS stripe_customer_id TEXT;
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS stripe_subscription_id TEXT;
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE public.api_keys ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

CREATE INDEX IF NOT EXISTS idx_api_keys_email ON public.api_keys (email);

-- ==========================================
-- 2. Tabella Regole WAF per Tenant
-- ==========================================
CREATE TABLE IF NOT EXISTS public.tenant_rules (
    key_hash TEXT PRIMARY KEY,
    mode TEXT NOT NULL DEFAULT 'block',
    ml_threshold DOUBLE PRECISION NOT NULL DEFAULT 0.75,
    allowlist_ips TEXT NOT NULL DEFAULT '[]',
    blocklist_ips TEXT NOT NULL DEFAULT '[]',
    exclude_paths TEXT NOT NULL DEFAULT '["/health","/metrics","/static"]',
    redact_pii BOOLEAN NOT NULL DEFAULT false,
    webhook_url TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ==========================================
-- 3. Tabella Log Attacchi Bloccati / Monitorati
-- ==========================================
CREATE TABLE IF NOT EXISTS public.log_attacchi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    key_hash TEXT DEFAULT '',
    api_key_usata TEXT NOT NULL,
    tipo_attacco TEXT NOT NULL,
    payload_malevolo TEXT NOT NULL,
    risk_score DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    latency_ms DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    level TEXT NOT NULL DEFAULT 'L1-Regex',
    client_ip TEXT NOT NULL DEFAULT ''
);

ALTER TABLE public.log_attacchi ADD COLUMN IF NOT EXISTS key_hash TEXT DEFAULT '';
ALTER TABLE public.log_attacchi ADD COLUMN IF NOT EXISTS risk_score DOUBLE PRECISION NOT NULL DEFAULT 1.0;
ALTER TABLE public.log_attacchi ADD COLUMN IF NOT EXISTS latency_ms DOUBLE PRECISION NOT NULL DEFAULT 0.0;
ALTER TABLE public.log_attacchi ADD COLUMN IF NOT EXISTS level TEXT NOT NULL DEFAULT 'L1-Regex';
ALTER TABLE public.log_attacchi ADD COLUMN IF NOT EXISTS client_ip TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_logs_key_created ON public.log_attacchi (key_hash, created_at DESC);

-- ==========================================
-- 4. Tabella Waitlist & Registrazioni Piani
-- ==========================================
CREATE TABLE IF NOT EXISTS public.waitlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_email TEXT NOT NULL,
    piano_scelto TEXT NOT NULL DEFAULT 'free',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_waitlist_email ON public.waitlist (cliente_email);

-- ==========================================
-- 5. Permessi API & Row Level Security (RLS)
-- ==========================================
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.api_keys TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.tenant_rules TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.log_attacchi TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.waitlist TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

ALTER TABLE public.api_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tenant_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.log_attacchi ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.waitlist ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "scudo_api_keys_policy" ON public.api_keys;
CREATE POLICY "scudo_api_keys_policy" ON public.api_keys
    FOR ALL TO anon, authenticated, service_role
    USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "scudo_tenant_rules_policy" ON public.tenant_rules;
CREATE POLICY "scudo_tenant_rules_policy" ON public.tenant_rules
    FOR ALL TO anon, authenticated, service_role
    USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "scudo_log_attacchi_policy" ON public.log_attacchi;
CREATE POLICY "scudo_log_attacchi_policy" ON public.log_attacchi
    FOR ALL TO anon, authenticated, service_role
    USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "scudo_waitlist_policy" ON public.waitlist;
CREATE POLICY "scudo_waitlist_policy" ON public.waitlist
    FOR ALL TO anon, authenticated, service_role
    USING (true) WITH CHECK (true);
